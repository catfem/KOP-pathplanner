      '            motor.configFactoryDefault()',
      '            motor.setNeutralMode(neutral)',
      '        for follower in self.left_followers:',
      '            follower.follow(self.left_leader)',
      '        for follower in self.right_followers:',
      '            follower.follow(self.right_leader)',
