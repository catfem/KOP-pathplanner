function pyBool(v: boolean): string {
  return v ? 'True' : 'False';
}

function pyList(values: number[]): string {
  return `[${values.map((v) => String(Math.round(v))).join(', ')}]`;
}

function docstring(lines: string[], indent = ''): string {
  const safe = lines.map((l) => l.replace(/"""/g, "'''"));
  return [`${indent}"""${safe[0]}`, ...safe.slice(1).map((l) => (l ? `${indent}${l}` : '')), `${indent}"""`].join('\n');
}

