function trajectoryFile(): string {
  return `"""Pre-computed wheel trajectories generated by KOP Path Planner."""

import bisect
from dataclasses import dataclass


@dataclass
class KopState:
    """One setpoint. Wheel positions are relative to the start of the trajectory."""

    time: float = 0.0
    x: float = 0.0
    y: float = 0.0
    heading: float = 0.0
    left_position: float = 0.0
    left_velocity: float = 0.0
    left_acceleration: float = 0.0
    right_position: float = 0.0
    right_velocity: float = 0.0
    right_acceleration: float = 0.0


class KopTrajectory:
    """Rows of (t, x, y, heading, left pos, left vel, left acc, right pos, right vel, right acc)."""

    COLUMNS = 10

    def __init__(self, rows):
        self._rows = [tuple(float(v) for v in row) for row in rows]
        if not self._rows or any(len(r) != self.COLUMNS for r in self._rows):
            raise ValueError("KopTrajectory needs rows of 10 values")
        self._times = [r[0] for r in self._rows]

    @property
    def total_time(self) -> float:
        return self._times[-1]

    def sample(self, t: float) -> KopState:
        """Linearly interpolates the setpoint at time t (clamped to the trajectory)."""
        rows = self._rows
        if t <= self._times[0]:
            return KopState(*rows[0])
        if t >= self._times[-1]:
            return KopState(*rows[-1])
        i = bisect.bisect_right(self._times, t)
        a, b = rows[i - 1], rows[i]
        span = b[0] - a[0]
        f = (t - a[0]) / span if span > 1e-9 else 0.0
        return KopState(*(a[k] + (b[k] - a[k]) * f for k in range(self.COLUMNS)))
`;
}

